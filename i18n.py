"""Idioma da interface (só stdlib, sem GUI). O texto em pt-BR é a própria chave: `t("Sair")` devolve
"Quit" em inglês. Com `**fmt`, a chave é um modelo (`t("Andar {n}", n=3)`). Sem `fmt`, um texto já montado
em pt (linhas de evento da masmorra, lápides antigas) é traduzido por modelo: "Pagou 12 ouro" casa com
"Pagou {n} ouro". Texto sem tradução (pets da comunidade) volta como veio.
Todo texto visível novo passa por `t()` e ganha entrada em EN (tests/test_idioma.py confere)."""
import re

LANGS = {"pt": "PT", "en": "EN"}
LANG = "pt"


def set_lang(lang):
    global LANG
    LANG = lang if lang in LANGS else "pt"


def t(text, **fmt):
    if LANG == "en":
        en = EN.get(text)
        if en is None and not fmt:
            return _by_template(text)
        text = en or text
    return text.format(**fmt) if fmt else text


_TEMPLATES = []


def _by_template(text):
    if not _TEMPLATES:
        for k, v in EN.items():
            if "{" in k:
                rx = re.escape(k)
                rx = re.sub(r"\\\{(\w+)\\\}", r"(?P<\1>.+?)", rx)
                _TEMPLATES.append((re.compile(rx + r"\Z"), v))
    for rx, en in _TEMPLATES:
        m = rx.match(text)
        if m:
            return en.format(**{k: t(v) for k, v in m.groupdict().items()})
    return text


