    for name, g in all_art().items():
        widths = {len(r) for r in g}
        assert len(widths) == 1, f"{name}: rows with different widths {widths}"
        for r in g:
            for ch in r:
                assert ch == "." or ch in PAL, f"{name}: unknown color {ch!r}"
