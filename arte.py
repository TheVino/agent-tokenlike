    for name, g in all_art().items():
        widths = {len(r) for r in g}
        assert len(widths) == 1, f"{name}: linhas com larguras diferentes {widths}"
        for r in g:
            for ch in r:
                assert ch == "." or ch in PAL, f"{name}: cor desconhecida {ch!r}"
