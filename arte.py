def _escada(n, c):
    """Escada de n degraus (2x2 px cada) subindo para a direita."""
    return ["".join(c if 2 * n - 1 - y < 2 * (x // 2 + 1) else "." for x in range(2 * n)) for y in range(2 * n)]


